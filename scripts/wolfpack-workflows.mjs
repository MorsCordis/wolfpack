#!/usr/bin/env node
// scripts/wolfpack-workflows.mjs — generate and check a consuming project's STAMPED copies of
// the pack's named workflows (.agents/workflows/*.js → <consumer>/.claude/workflows/*.js).
// install.sh calls it; the workflows' run-start probe runs `check --json`.
//
// WHY: Claude Code runs a named workflow from the consuming project's .claude/workflows/, so
// every consumer holds a copy of each pack workflow. An unstamped copy cannot say which pack
// it came from, and a stale one silently runs old code. This script replaces the old
// namespace-transforming sync: a generated copy is the canonical file byte for byte, except
// that its ONE stamp line
//     const WOLFPACK_STAMP = null // wolfpack-stamp — …
// becomes
//     const WOLFPACK_STAMP = {"workflow":…,"commit":…,"version":…,"source":"sha256:…"} // wolfpack-stamp (…)
// There is no path transform: worktree paths come from wolfpack-config.md → Worktree root and
// role skills from the pack itself.
//
// FRESHNESS (content identity, not pack HEAD). A copy is CURRENT iff
//   (a) its stamp parses, (b) stamp.source === sha256(<pack>/.agents/workflows/<name>) now, and
//   (c) its bytes === render(canonical, its own stamp) (catches a hand edit under an intact stamp).
// commit/version are display only, so an unrelated pack commit (or a merge commit) never marks
// a copy stale; a change to the canonical workflow does.
//
// THE PACK ITSELF. The canonical files carry the null stamp. A consumer workflow whose realpath
// is the pack's canonical file (wolfpack's .claude/workflows is a link to ../.agents/workflows)
// is reported 'canonical' and is never written. A canonical run cannot detect the
// named-workflow session cache on itself (there is no stamp to compare) — documented limit.
//
// CLI: node scripts/wolfpack-workflows.mjs generate|check [--pack <dir>] --consumer <dir> [--json]
//   --pack defaults to this script's repo root.
//   generate — exit 0, or 2 on any refusal (foreign link) or error. A canonical target is
//              reported "canonical (pack itself) — nothing to generate" (exit 0).
//   check    — read-only. exit 0 every workflow current|canonical · 1 any other state ·
//              2 usage/error (the message names the path). --json prints checkAll() as ONE object.

import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { existsSync, lstatSync, mkdirSync, readdirSync, readFileSync, realpathSync, renameSync, rmSync, statSync, writeFileSync, chmodSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

export const STAMP_RE = /^const WOLFPACK_STAMP = (null|\{.*\}) \/\/ wolfpack-stamp\b.*$/m
const STAMP_RE_ALL = new RegExp(STAMP_RE.source, 'gm')
export const CANONICAL_STAMP_LINE = 'const WOLFPACK_STAMP = null // wolfpack-stamp — generated copies carry {workflow, commit, version, source}; see scripts/wolfpack-workflows.mjs'
export const STATES_OK = ['current', 'canonical']

const HEX40 = /^[0-9a-f]{40}$/
const SOURCE_RE = /^sha256:[0-9a-f]{64}$/

export function defaultPack() {
  return resolve(dirname(fileURLToPath(import.meta.url)), '..')
}

export function sourceHash(text) {
  return 'sha256:' + createHash('sha256').update(text).digest('hex')
}

export function stampLine(stamp) {
  return `const WOLFPACK_STAMP = ${JSON.stringify(stamp)} // wolfpack-stamp (generated by the pack's install.sh — do not hand-edit; the run start checks it)`
}

const stampMatches = (text) => [...String(text).matchAll(STAMP_RE_ALL)]

export function render(canonicalText, stamp) {
  const m = stampMatches(canonicalText)
  if (m.length !== 1) throw new Error(`render: the canonical workflow must carry exactly one wolfpack-stamp line, found ${m.length}`)
  if (m[0][1] !== 'null') throw new Error('render: the canonical workflow\'s stamp line is not the null form — refusing to stamp an already-stamped file')
  const out = canonicalText.slice(0, m[0].index) + stampLine(stamp) + canonicalText.slice(m[0].index + m[0][0].length)
  if (!out.startsWith('export const meta')) throw new Error('render: the result does not start with \'export const meta\' — refusing (the harness would not load it)')
  return out
}

export function parseStamp(text) {
  const m = stampMatches(text)
  if (m.length === 0) return { stamp: null, error: 'no wolfpack-stamp line' }
  if (m.length > 1) return { stamp: null, error: `${m.length} wolfpack-stamp lines (exactly one allowed)` }
  if (m[0][1] === 'null') return { stamp: null, error: 'null stamp (the canonical form) in a copy' }
  let s
  try { s = JSON.parse(m[0][1]) } catch (e) { return { stamp: null, error: `stamp is not valid JSON (${e.message})` } }
  if (!s || typeof s !== 'object' || Array.isArray(s)) return { stamp: null, error: 'stamp is not an object' }
  const bad = []
  if (typeof s.workflow !== 'string' || !s.workflow) bad.push('workflow')
  if (typeof s.commit !== 'string' || !HEX40.test(s.commit)) bad.push('commit (40-hex)')
  if (typeof s.version !== 'string' || !s.version) bad.push('version')
  if (typeof s.source !== 'string' || !SOURCE_RE.test(s.source)) bad.push('source (sha256:<64-hex>)')
  if (bad.length) return { stamp: null, error: `stamp field(s) missing or malformed: ${bad.join(', ')}` }
  return { stamp: s, error: null }
}

export function packInfo(pack) {
  const git = (args) => execFileSync('git', ['-C', pack, ...args], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }).trim()
  let version
  try { version = git(['describe', '--tags', '--match', 'v[0-9]*']) } catch {
    throw new Error(`cannot read the pack version at ${pack} (no tags reachable) — fix: git -C '${pack}' fetch --tags`)
  }
  let commit
  try { commit = git(['rev-parse', 'HEAD']) } catch (e) {
    throw new Error(`cannot read the pack commit at ${pack} (git rev-parse HEAD failed: ${String(e.stderr || e.message).trim()})`)
  }
  if (!version || !HEX40.test(commit)) throw new Error(`cannot read the pack version/commit at ${pack} (got '${version}' / '${commit}')`)
  return { version, commit }
}

export function workflowNames(pack) {
  const dir = join(pack, '.agents', 'workflows')
  let names
  try { names = readdirSync(dir) } catch { throw new Error(`no canonical workflows directory at ${dir}`) }
  names = names.filter((n) => n.endsWith('.js')).sort()
  if (!names.length) throw new Error(`no canonical workflows (*.js) in ${dir}`)
  return names
}

const isLink = (p) => { try { return lstatSync(p).isSymbolicLink() } catch { return false } }
const lexists = (p) => { try { lstatSync(p); return true } catch { return false } }
const real = (p) => { try { return realpathSync(p) } catch { return null } }

// Shell-quote one word ('…' with an embedded ' as '\'') so a path with a quote, space or $ round-trips
// when the fix line is pasted. Byte-identical to the old output for a quote-free path.
const shq = (s) => `'${String(s).replace(/'/g, `'\\''`)}'`
export function installFix(pack, consumer) {
  return `bash ${shq(`${pack}/install.sh`)} --consumer ${shq(consumer)}`
}

export function checkWorkflow({ pack, consumer, name }) {
  pack = resolve(pack)
  consumer = resolve(consumer)
  const canonicalPath = join(pack, '.agents', 'workflows', name)
  let canonicalText
  try { canonicalText = readFileSync(canonicalPath, 'utf8') } catch { throw new Error(`canonical workflow not found: ${canonicalPath}`) }
  const canonicalSource = sourceHash(canonicalText)
  const dir = join(consumer, '.claude', 'workflows')
  const file = join(dir, name)
  const fix = installFix(pack, consumer)
  const out = (state, extra = {}) => ({ name, file, state, stamp: null, canonicalSource, fix: STATES_OK.includes(state) ? null : fix, ...extra })

  const fileReal = existsSync(file) ? real(file) : null
  if (fileReal && fileReal === real(canonicalPath)) return out('canonical')
  if (isLink(file) || isLink(dir)) {
    return out('foreign-link', { target: fileReal, fix: `remove ${file} or point WOLFPACK_HOME at the pack it links to` })
  }
  if (!lexists(file)) return out('missing')
  let text
  try { text = readFileSync(file, 'utf8') } catch (e) { throw new Error(`cannot read ${file}: ${e.message}`) }
  const { stamp, error } = parseStamp(text)
  if (!stamp) return out('unstamped', { error })
  if (stamp.source !== canonicalSource) return out('stale', { stamp })
  if (text !== render(canonicalText, stamp)) return out('modified', { stamp })
  return out('current', { stamp })
}

export function checkAll({ pack, consumer }) {
  pack = resolve(pack)
  consumer = resolve(consumer)
  if (!existsSync(consumer) || !statSync(consumer).isDirectory()) throw new Error(`consumer is not a directory: ${consumer}`)
  const { version, commit } = packInfo(pack)
  const workflows = workflowNames(pack).map((name) => checkWorkflow({ pack, consumer, name }))
  return { ok: workflows.every((w) => STATES_OK.includes(w.state)), pack, packVersion: version, packCommit: commit, consumer, workflows }
}

export function generate({ pack, consumer }) {
  pack = resolve(pack)
  consumer = resolve(consumer)
  if (!existsSync(consumer) || !statSync(consumer).isDirectory()) throw new Error(`consumer is not a directory: ${consumer}`)
  const { version, commit } = packInfo(pack)
  const claudeDir = join(consumer, '.claude')
  const dir = join(claudeDir, 'workflows')
  const results = []
  for (const name of workflowNames(pack)) {
    const c = checkWorkflow({ pack, consumer, name })
    const file = c.file
    if (c.state === 'canonical') { results.push({ name, file, action: 'canonical', refused: false }); continue }
    if (c.state === 'foreign-link') { results.push({ name, file, action: 'refused', refused: true, reason: `${file} is a link to ${c.target || 'a missing target'}, not this pack's canonical — fix: ${c.fix}` }); continue }
    if (isLink(dir) || isLink(claudeDir)) {
      results.push({ name, file, action: 'refused', refused: true, reason: `${isLink(dir) ? dir : claudeDir} is a symlink — refusing to write through it` })
      continue
    }
    const canonicalText = readFileSync(join(pack, '.agents', 'workflows', name), 'utf8')
    const bytes = render(canonicalText, { workflow: name, commit, version, source: sourceHash(canonicalText) })
    const existed = existsSync(file)
    if (existed && readFileSync(file, 'utf8') === bytes) { results.push({ name, file, action: 'unchanged', refused: false }); continue }
    mkdirSync(dir, { recursive: true })
    const tmp = join(dir, `.${name}.tmp-${process.pid}`)
    try {
      writeFileSync(tmp, bytes, { mode: 0o644 })
      chmodSync(tmp, 0o644)
      renameSync(tmp, file)
    } catch (e) {
      try { rmSync(tmp, { force: true }) } catch {}
      throw new Error(`cannot write ${file}: ${e.message}`)
    }
    results.push({ name, file, action: existed ? 'regenerated' : 'generated', refused: false })
  }
  return { ok: results.every((r) => !r.refused), pack, packVersion: version, packCommit: commit, consumer, results }
}

function checkLine(w) {
  const at = w.stamp ? `${w.stamp.version} @ ${w.stamp.commit.slice(0, 12)}` : ''
  switch (w.state) {
    case 'current': return `✓ current ${w.file} (${at})`
    case 'canonical': return `✓ canonical ${w.file} (the pack's own file)`
    case 'stale': return `✗ stale ${w.file} (stamped ${at}; pack canonical changed) — fix: ${w.fix}`
    case 'modified': return `✗ modified ${w.file} (stamped ${at}; stamp intact but the bytes are not the generated copy) — fix: ${w.fix}`
    case 'unstamped': return `✗ unstamped ${w.file} (${w.error}) — fix: ${w.fix}`
    case 'missing': return `✗ missing ${w.file} — fix: ${w.fix}`
    case 'foreign-link': return `✗ foreign-link ${w.file} (→ ${w.target || 'missing target'}) — fix: ${w.fix}`
    default: return `✗ ${w.state} ${w.file} — fix: ${w.fix}`
  }
}

function usage(msg) {
  if (msg) process.stderr.write(`✗ ${msg}\n`)
  process.stderr.write('usage: node scripts/wolfpack-workflows.mjs generate|check [--pack <dir>] --consumer <dir> [--json]\n')
  process.exit(2)
}

function main(argv) {
  const [cmd, ...rest] = argv
  if (cmd !== 'generate' && cmd !== 'check') usage(cmd ? `unknown command: ${cmd}` : 'missing command')
  let pack = defaultPack(), consumer = null, json = false
  for (let i = 0; i < rest.length; i++) {
    const a = rest[i]
    if (a === '--json') json = true
    else if (a === '--pack' || a === '--consumer') {
      const v = rest[++i]
      if (v === undefined || v === '' || v.startsWith('--')) usage(`${a} needs a value`)
      if (a === '--pack') pack = v; else consumer = v
    } else usage(`unknown argument: ${a}`)
  }
  if (!consumer) usage('--consumer <dir> is required')
  try {
    if (cmd === 'check') {
      const r = checkAll({ pack, consumer })
      if (json) process.stdout.write(`${JSON.stringify(r)}\n`)
      else for (const w of r.workflows) process.stdout.write(`${checkLine(w)}\n`)
      process.exit(r.ok ? 0 : 1)
    }
    const r = generate({ pack, consumer })
    if (json) process.stdout.write(`${JSON.stringify(r)}\n`)
    else {
      for (const x of r.results) {
        if (x.action === 'canonical') process.stdout.write(`✓ canonical (pack itself) — nothing to generate: ${x.file}\n`)
        else if (x.refused) process.stdout.write(`✗ refused ${x.file}: ${x.reason}\n`)
        else process.stdout.write(`${x.action} ${x.file} (${r.packVersion} @ ${r.packCommit.slice(0, 12)})\n`)
      }
    }
    process.exit(r.ok ? 0 : 2)
  } catch (e) {
    process.stderr.write(`✗ wolfpack-workflows ${cmd}: ${e.message}\n`)
    process.exit(2)
  }
}

if (process.argv[1] && real(process.argv[1]) === real(fileURLToPath(import.meta.url))) main(process.argv.slice(2))
